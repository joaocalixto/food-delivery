-- =====================================================================
-- Script de inicializacao do banco do restaurant-service
-- Cria o schema (caso o app ainda nao tenha subido) e popula dados de exemplo.
--
-- Como usar: monte este arquivo em /docker-entrypoint-initdb.d/ do Postgres
-- (ele roda automaticamente na PRIMEIRA criacao do banco). Veja PULL-E-RODAR.md.
--
-- Observacao: o app usa ddl-auto=update, entao se as tabelas ja existirem ele
-- apenas as reaproveita. O CREATE ... IF NOT EXISTS torna o script seguro
-- de rodar antes ou depois do app.
-- =====================================================================

CREATE TABLE IF NOT EXISTS restaurants (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255),
    cuisine VARCHAR(255),
    address VARCHAR(255),
    open    BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS menu_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255),
    description   VARCHAR(255),
    price_cents   BIGINT,
    available     BOOLEAN DEFAULT TRUE,
    restaurant_id BIGINT REFERENCES restaurants(id)
);

